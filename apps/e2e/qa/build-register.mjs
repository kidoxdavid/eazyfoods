// Turns the audit results into the QA register in docs/MOBILE_QA_REGISTER.md.
// Usage: node qa/build-register.mjs            (reads qa/results.json, qa/routes.json, qa/baseline.json, qa/progress.md)
//        node qa/build-register.mjs --baseline (also saves today's counts as the "before" figures)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const rows = JSON.parse(readFileSync(resolve(here, 'results.json'), 'utf8'));
const routes = JSON.parse(readFileSync(resolve(here, 'routes.json'), 'utf8'));
const progress = existsSync(resolve(here, 'progress.md')) ? readFileSync(resolve(here, 'progress.md'), 'utf8') : '';

const count = (rs) => {
  const c = { critical: 0, high: 0, info: 0, kinds: {}, routesWithIssues: new Set() };
  for (const r of rs) for (const [vp, list] of Object.entries(r.issues)) for (const i of list) {
    c[i.severity]++; c.kinds[i.kind] = (c.kinds[i.kind] ?? 0) + 1; if (i.severity !== 'info') c.routesWithIssues.add(r.app + r.url);
  }
  return c;
};
const now = count(rows);
const baselinePath = resolve(here, 'baseline.json');
if (process.argv.includes('--baseline')) writeFileSync(baselinePath, JSON.stringify({ date: new Date().toISOString().slice(0, 10), critical: now.critical, high: now.high, info: now.info, kinds: now.kinds, routesWithIssues: now.routesWithIssues.size, audited: rows.filter((r) => r.status !== 'unresolved').length }, null, 1));
const before = existsSync(baselinePath) ? JSON.parse(readFileSync(baselinePath, 'utf8')) : null;

const apps = [...new Set(routes.map((r) => r.app))];
const audited = rows.filter((r) => r.status !== 'unresolved');
const lines = [];
lines.push('# Mobile responsiveness QA register', '',
  'Generated by `apps/e2e/qa/build-register.mjs` from the audit in `apps/e2e/tests/exhaustive/responsive-audit.test.ts`. Do not edit by hand: re-run the audit and the generator.', '',
  '**How it was tested:** a headless Chromium browser at 320, 360, 390, 430, 768, 1024, 1280 and 1440 px wide, plus two phone landscape sizes (667x375, 844x390). This is browser emulation. **No physical iPhone or Android device was used**, so anything that depends on a real device is listed under "needs a physical device" below.', '',
  '## Summary', '',
  '| | Before | Now |', '|---|---|---|',
  `| Apps | ${apps.length} | ${apps.length} |`, `| Routes in the apps' routers | ${routes.length} | ${routes.length} |`,
  `| Routes audited | ${before?.audited ?? '-'} | ${audited.length} |`,
  `| Critical findings (sideways scroll, elements off screen, overlaps, date fields) | ${before?.critical ?? '-'} | ${now.critical} |`,
  `| High findings (inputs under 16px, text clipped, targets under 24px) | ${before?.high ?? '-'} | ${now.high} |`,
  `| Routes with a critical or high finding | ${before?.routesWithIssues ?? '-'} | ${now.routesWithIssues.size} |`,
  `| Controls between 24 and 44 px (information only) | ${before?.info ?? '-'} | ${now.info} |`, '');
lines.push('### Findings by kind (now)', '', '| Kind | Count |', '|---|---|');
for (const [k, v] of Object.entries(now.kinds).sort((a, b) => b[1] - a[1])) lines.push(`| ${k} | ${v} |`);
lines.push('', '## By app', '', '| App | Routes | Audited | Redirected | Needs sample data | Clean | With findings |', '|---|---|---|---|---|---|---|');
for (const a of apps) {
  const rr = rows.filter((r) => r.app === a); const au = rr.filter((r) => r.status !== 'unresolved');
  const bad = au.filter((r) => Object.values(r.issues).some((l) => l.some((i) => i.severity !== 'info')));
  lines.push(`| ${a} | ${routes.filter((r) => r.app === a).length} | ${au.length} | ${rr.filter((r) => r.status === 'redirected').length} | ${rr.filter((r) => r.status === 'unresolved').length} | ${au.length - bad.length} | ${bad.length} |`);
}
const open = audited.filter((r) => Object.values(r.issues).some((l) => l.some((i) => i.severity !== 'info')));
lines.push('', '## Open findings by route', '');
if (!open.length) lines.push('None.');
else {
  lines.push('| App | Route | Finding | Widths | Detail |', '|---|---|---|---|---|');
  for (const r of open) {
    const byKind = {};
    for (const [vp, list] of Object.entries(r.issues)) for (const i of list) if (i.severity !== 'info') (byKind[i.kind] ??= { vps: [], d: i.detail }).vps.push(vp.replace(' landscape', 'L'));
    for (const [k, v] of Object.entries(byKind)) lines.push(`| ${r.app} | \`${r.url}\` | ${k} | ${v.vps.join(', ')} | ${v.d.replace(/\|/g, '/').slice(0, 140)} |`);
  }
}
const clean = audited.filter((r) => !open.includes(r));
lines.push('', '## Routes that passed mobile QA (no critical or high findings at any width)', '', clean.map((r) => `\`${r.url}\``).join(', ') || 'None.');
const un = rows.filter((r) => r.status === 'unresolved');
lines.push('', '## Routes not audited (needs data that the test database does not have)', '', un.map((r) => `\`${r.url}\``).join(', ') || 'None.');
const rd = rows.filter((r) => r.status === 'redirected');
lines.push('', '## Routes that redirect (audited at the page they land on)', '', rd.map((r) => `\`${r.url}\` -> \`${r.landed}\``).join('; ') || 'None.');
lines.push('', '## Needs a physical device', '',
  '- The barcode scanner (camera, torch, zoom): emulation can only play a recorded video.',
  '- Native date, time and month pickers: each phone draws its own; emulation checks the field size and position, not the pop-up.',
  '- Card payment fields (Stripe): the secure iframe behaves differently on real iOS Safari.',
  '- Maps and live driver tracking.',
  '- Safe-area insets (notch, home indicator), on-screen keyboard resizing, and iOS Safari input zoom itself. The 16px rule that prevents the zoom is verified; the zoom behaviour is not.',
  '- Pinch zoom is deliberately left enabled (no `maximum-scale`, no `user-scalable=no`).', '');
if (progress) lines.push('## Progress log', '', progress.trim(), '');
writeFileSync(resolve(here, '../../../docs/MOBILE_QA_REGISTER.md'), lines.join('\n'));
console.log('register written:', audited.length, 'audited,', now.critical, 'critical,', now.high, 'high');
